public class EdadFutura {
    public static void main(String[] args) {
        int edadActual = 17;
        int aniosAPasar = 5;

        int edadFutura = edadActual + aniosAPasar;

        System.out.println("Edad actual: " + edadActual);
        System.out.println("Dentro de " + aniosAPasar + " años tendrás: " + edadFutura + " años");
    }
}